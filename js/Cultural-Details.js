/* =========================================================
   NAVIGATION
========================================================= */

function updateNavigation(index) {

    const previousIndex =
        index - 1;

    const nextIndex =
        index + 1;


    /*
    |--------------------------------------------------------------------------
    | Previous
    |--------------------------------------------------------------------------
    */

    if (previousIndex >= 0) {

        const previous =
            timelineData[previousIndex];

        previousTitle.textContent =
            previous.title;

        previousPeriod.href =
            `Cultural-Details.html?period=${previous.id}`;

        previousPeriod.style.visibility =
            "visible";

    } else {

        previousTitle.textContent =
            "البداية";

        previousPeriod.removeAttribute("href");

        previousPeriod.style.visibility =
            "hidden";
    }


    /*
    |--------------------------------------------------------------------------
    | Next
    |--------------------------------------------------------------------------
    */

    if (nextIndex < timelineData.length) {

        const next =
            timelineData[nextIndex];

        nextTitle.textContent =
            next.title;

        nextPeriod.href =
            `Cultural-Details.html?period=${next.id}`;

        nextPeriod.style.visibility =
            "visible";

    } else {

        nextTitle.textContent =
            "النهاية";

        nextPeriod.removeAttribute("href");

        nextPeriod.style.visibility =
            "hidden";
    }

}


/* =========================================================
   RELATED PERIODS
========================================================= */

function updateRelatedPeriods(index) {

    relatedPeriods.innerHTML = "";


    /*
    |--------------------------------------------------------------------------
    | نعرض 3 مراحل قريبة من المرحلة الحالية
    |--------------------------------------------------------------------------
    */

    const relatedIndexes = [];


    if (index > 0) {
        relatedIndexes.push(index - 1);
    }


    if (
        index + 1 <
        timelineData.length
    ) {
        relatedIndexes.push(index + 1);
    }


    /*
    |--------------------------------------------------------------------------
    | إذا كنا بالبداية أو النهاية نضيف مرحلة إضافية
    |--------------------------------------------------------------------------
    */

    if (
        relatedIndexes.length < 3 &&
        index + 2 <
        timelineData.length
    ) {
        relatedIndexes.push(index + 2);
    }


    if (
        relatedIndexes.length < 3 &&
        index - 2 >= 0
    ) {
        relatedIndexes.unshift(index - 2);
    }


    relatedIndexes
        .slice(0, 3)
        .forEach(relatedIndex => {

            const item =
                timelineData[relatedIndex];

            const card =
                document.createElement("a");

            card.href =
                `Cultural-Details.html?period=${item.id}`;

            card.className =
                "related-card";


            card.innerHTML = `

                <img
                    src="${item.image}"
                    alt="${item.title}"
                    loading="lazy"
                >

                <div class="related-card-content">

                    <span class="related-card-date">
                        ${item.date}
                    </span>

                    <h3>
                        ${item.title}
                    </h3>

                    <span class="related-card-period">
                        ${item.period}
                    </span>

                </div>

            `;


            relatedPeriods.appendChild(card);

        });

}


/* =========================================================
   IMAGE FALLBACK
========================================================= */

function setupImageFallback() {

    const images =
        document.querySelectorAll("img");

    images.forEach(image => {

        image.addEventListener(
            "error",
            function () {

                this.style.display =
                    "none";

                const parent =
                    this.parentElement;

                if (parent) {

                    parent.classList.add(
                        "image-unavailable"
                    );

                }

            }
        );

    });

}


/* =========================================================
   KEYBOARD NAVIGATION
========================================================= */

document.addEventListener(
    "keydown",
    event => {

        if (event.key === "ArrowLeft") {

            if (
                currentIndex + 1 <
                timelineData.length
            ) {

                const next =
                    timelineData[currentIndex + 1];

                window.location.href =
                    `Cultural-Details.html?period=${next.id}`;
            }

        }


        if (event.key === "ArrowRight") {

            if (currentIndex - 1 >= 0) {

                const previous =
                    timelineData[currentIndex - 1];

                window.location.href =
                    `Cultural-Details.html?period=${previous.id}`;
            }

        }

    }
);


/* =========================================================
   INITIALIZE
========================================================= */

function initializePage() {

    const current =
        timelineData[currentIndex];

    if (!current) {
        return;
    }

    updatePage(
        current,
        currentIndex
    );

    setupImageFallback();


    /*
    |--------------------------------------------------------------------------
    | Page reveal
    |--------------------------------------------------------------------------
    */

    requestAnimationFrame(() => {

        document.body.classList.add(
            "details-page-ready"
        );

    });

}


/* =========================================================
   START
========================================================= */

initializePage();